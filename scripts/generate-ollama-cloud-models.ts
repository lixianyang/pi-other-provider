import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import type { Model } from "@earendil-works/pi-ai";
import { OllamaCloudClient } from "../src/providers/ollama-cloud/client.ts";
import { toOllamaCloudModel } from "../src/providers/ollama-cloud/model-mapper.ts";

const outputPath = fileURLToPath(new URL("../src/providers/ollama-cloud/models.generated.ts", import.meta.url));
const inspections = await new OllamaCloudClient().discoverModels(new AbortController().signal);
const failed = inspections.filter((inspection) => !inspection.ok);
if (failed.length > 0) {
	throw new Error(`Could not inspect ${failed.length} Ollama Cloud model(s); generated catalog was not changed`);
}

const models = inspections
	.flatMap((inspection) => {
		if (!inspection.ok) return [];
		const model = toOllamaCloudModel(inspection.id, inspection.details);
		return model ? [model] : [];
	})
	.sort((left, right) => left.id.localeCompare(right.id)) satisfies Model<"openai-completions">[];

if (models.length === 0)
	throw new Error("Ollama Cloud returned no tool-capable models; generated catalog was not changed");

const source = `/** Generated by \`npm run generate:ollama-cloud-models\`. Do not edit manually. */
import type { Model } from "@earendil-works/pi-ai";

export const GENERATED_OLLAMA_CLOUD_MODELS: readonly Model<"openai-completions">[] = ${JSON.stringify(models, null, "\t")};
`;

await writeFile(outputPath, source, "utf8");
process.stdout.write(`Generated ${models.length} Ollama Cloud models.\n`);
